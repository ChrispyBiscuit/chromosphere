"""Early-reflection tap tables from a shoebox room (image-source method, pyroomacoustics).

Writes dsp/er/er_default_table.h. Offline tool; not shipped in the plugin.
Usage: python3 room_model.py [--room 8 6 3.5] [--src 2 2 1.5] [--lis 5.5 3.5 1.5] [--taps 64]
"""
import argparse
import numpy as np
import pyroomacoustics as pra

C = 343.0


def er_taps(room_dim, src, lis, absorption=0.25, max_order=4, taps=64, facing_deg=0.0):
    room = pra.ShoeBox(room_dim, fs=48000, materials=pra.Material(absorption), max_order=max_order)
    room.add_source(src)
    room.add_microphone(lis)
    room.image_source_model()
    s = room.sources[0]
    imgs = np.asarray(s.images)                     # (3, n)
    damp = np.asarray(s.damping)[0]                 # broadband wall loss per image
    vec = imgs - np.asarray(lis)[:, None]
    dist = np.linalg.norm(vec, axis=0)
    order = np.argsort(dist)
    order = order[1:]                               # drop the direct sound
    order = order[:taps]
    gain = damp[order] / dist[order]
    gain /= gain.max()
    az = np.arctan2(vec[1, order], vec[0, order]) - np.deg2rad(facing_deg)
    pan = np.sin(az)                                # -1 left .. +1 right
    direct = np.linalg.norm(np.asarray(src) - np.asarray(lis))
    delay = (dist[order] - direct) / C              # seconds after the direct sound
    first = delay.min()
    return delay, gain, pan, first


def write_header(path, delay, gain, pan, meta):
    with open(path, "w") as f:
        f.write("// Generated by tools/room_model.py -- do not edit.\n")
        f.write("// %s\n#pragma once\n\nnamespace fr {\n\n" % meta)
        f.write("struct ErTap { float delaySec; float gain; float pan; };\n")
        f.write("constexpr int kErDefaultCount = %d;\n" % len(delay))
        f.write("constexpr ErTap kErDefaultTable[kErDefaultCount] = {\n")
        for d, g, p in zip(delay, gain, pan):
            f.write("    {%.7ff, %.6ff, %.5ff},\n" % (d, g, p))
        f.write("};\n\n}  // namespace fr\n")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--room", type=float, nargs=3, default=[8.0, 6.0, 3.5])
    ap.add_argument("--src", type=float, nargs=3, default=[2.0, 2.0, 1.5])
    ap.add_argument("--lis", type=float, nargs=3, default=[5.5, 3.5, 1.5])
    ap.add_argument("--taps", type=int, default=64)
    ap.add_argument("--out", default="../dsp/er/er_default_table.h")
    a = ap.parse_args()
    d, g, p, first = er_taps(a.room, a.src, a.lis, taps=a.taps)
    meta = "room %s m, source %s, listener %s; first reflection %.1f ms after direct" % (a.room, a.src, a.lis, first * 1000)
    write_header(a.out, d, g, p, meta)
    print(meta, "| taps", len(d), "| span %.1f ms" % (d[-1] * 1000))
