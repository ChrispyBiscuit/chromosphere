"""Derive INFRA's red solar images from Chromosphere | EXO's orange ones.

The EXO images (corona_bg.jpg, solar_limb.png; see EXO's docs/SOLAR_ASSETS.md) were generated by the project
owner. INFRA shows the same star in infrared: the warm highlights move from solar orange to red, the darks stay
neutral. Usage: python3 make_red_assets.py <exo assets/img dir> <infra assets/img dir>
"""
import sys
import numpy as np
from PIL import Image


def redshift(rgb, strength=1.0):
    x = rgb.astype(np.float32) / 255.0
    lum = 0.2126 * x[..., 0] + 0.7152 * x[..., 1] + 0.0722 * x[..., 2]
    # Warmth of the source pixel (orange highlights have r >> b); dark neutral pixels keep their grey.
    warm = np.clip((x[..., 0] - x[..., 2]) * 4.0, 0.0, 1.0) * strength
    grey = np.stack([lum * 1.02, lum * 0.98, lum * 1.0], axis=-1)
    # Infrared ramp: crimson in the mid tones, a hot rose-white only at the very top.
    hot = np.clip((lum - 0.55) * 2.2, 0.0, 1.0)[..., None]
    red = np.stack([np.clip(lum * 2.6, 0, 1), lum * 0.30, lum * 0.24], axis=-1)
    red = red * (1 - hot) + np.array([1.0, 0.78, 0.72]) * hot
    out = grey * (1 - warm[..., None]) + red * warm[..., None]
    return (np.clip(out, 0, 1) * 255 + 0.5).astype(np.uint8)


def main(src, dst):
    cor = np.array(Image.open(f"{src}/corona_bg.jpg").convert("RGB"))
    Image.fromarray(redshift(cor)).save(f"{dst}/corona_bg.jpg", quality=88)
    limb = np.array(Image.open(f"{src}/solar_limb.png").convert("RGBA"))
    rgb = redshift(limb[..., :3], 1.0)
    Image.fromarray(np.dstack([rgb, limb[..., 3]])).save(f"{dst}/solar_limb.png", optimize=True)


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
