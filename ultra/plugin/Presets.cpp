#include "Presets.h"
#include "PluginProcessor.h"
#include <UltraData.h>

PresetManager::PresetManager(UltraProcessor& p) : proc_(p) { reload(); }

juce::File PresetManager::userFolder() const {
    return juce::File::getSpecialLocation(juce::File::userApplicationDataDirectory).getChildFile("ChromosphereUltra").getChildFile("Presets");
}

bool PresetManager::isGrooveParam(const juce::String& id) { return id == "pattern" || id == "swing" || id == "tempo" || id == "fill"; }

void PresetManager::reload() {
    const juce::String keep = currentName();
    presets_.clear();
    const juce::var root = juce::JSON::parse(juce::String::fromUTF8(UltraData::presets_json, UltraData::presets_jsonSize));
    if (auto* list = root["presets"].getArray())
        for (const auto& item : *list) {
            Preset p;
            p.name = item["name"].toString(); p.category = item["category"].toString();
            p.description = item["description"].toString(); p.author = item["author"].toString();
            if (auto* t = item["tags"].getArray()) for (const auto& s : *t) p.tags.add(s.toString());
            if (auto* o = item["params"].getDynamicObject()) p.params = o->getProperties();
            p.patterns = item["patterns"]; p.names = item["names"];
            presets_.push_back(std::move(p));
        }
    for (const auto& f : userFolder().findChildFiles(juce::File::findFiles, false, "*.ulpreset")) {
        if (auto xml = juce::parseXML(f)) {
            if (!xml->hasTagName("ULPreset")) continue;
            Preset p;
            p.factory = false; p.file = f;
            p.name = xml->getStringAttribute("name", f.getFileNameWithoutExtension());
            p.category = xml->getStringAttribute("category", "User");
            p.description = xml->getStringAttribute("description");
            p.tags.addTokens(xml->getStringAttribute("tags"), ",", "");
            p.tags.trim(); p.tags.removeEmptyStrings();
            for (auto* e : xml->getChildWithTagNameIterator("PARAM")) p.params.set(e->getStringAttribute("id"), e->getDoubleAttribute("value"));
            if (auto* pe = xml->getChildByName("PATTERNS")) p.patterns = juce::JSON::parse(pe->getAllSubText());
            if (auto* ne = xml->getChildByName("NAMES")) p.names = juce::JSON::parse(ne->getAllSubText());
            presets_.push_back(std::move(p));
        }
    }
    current_ = indexOf(keep);
}

int PresetManager::indexOf(const juce::String& name) const {
    for (size_t i = 0; i < presets_.size(); ++i) if (presets_[i].name == name) return (int)i;
    return -1;
}

juce::String PresetManager::currentName() const {
    if (current_ >= 0 && current_ < (int)presets_.size()) return presets_[(size_t)current_].name;
    return generatedName_;
}
juce::String PresetManager::currentCategory() const {
    if (current_ >= 0 && current_ < (int)presets_.size()) return presets_[(size_t)current_].category;
    return generatedCategory_;
}
juce::String PresetManager::currentDescription() const {
    if (current_ >= 0 && current_ < (int)presets_.size()) return presets_[(size_t)current_].description;
    return generatedName_.isNotEmpty() ? juce::String("Generated by Ignite. Save it to keep it.") : juce::String();
}
void PresetManager::setCurrentName(const juce::String& n) {
    current_ = indexOf(n);
    if (current_ < 0) { generatedName_ = n; generatedCategory_ = {}; }
}

void PresetManager::applyOne(juce::RangedAudioParameter& prm, const juce::var& v) {
    float plain;
    if (auto* choice = dynamic_cast<juce::AudioParameterChoice*>(&prm)) {
        plain = v.isString() ? (float)choice->choices.indexOf(v.toString()) : (float)(double)v;
        if (plain < 0) plain = prm.convertFrom0to1(prm.getDefaultValue());
    } else if (v.isBool()) plain = (bool)v ? 1.f : 0.f;
    else plain = (float)(double)v;
    prm.setValueNotifyingHost(prm.convertTo0to1(plain));
}

void PresetManager::setParameters(const juce::NamedValueSet& values) {
    for (auto* prm : proc_.getParameters()) {
        auto* r = dynamic_cast<juce::RangedAudioParameter*>(prm);
        if (!r) continue;
        const juce::String id = r->getParameterID();
        if (keepPatterns && isGrooveParam(id)) continue;
        if (values.contains(id)) applyOne(*r, values[id]);
        else r->setValueNotifyingHost(r->getDefaultValue());
    }
}

bool PresetManager::apply(int index) {
    if (index < 0 || index >= (int)presets_.size()) return false;
    const Preset& p = presets_[(size_t)index];
    proc_.undoManager.beginNewTransaction("Load preset " + p.name);
    setParameters(p.params);
    if (!keepPatterns) proc_.patterns.patternsFromVar(p.patterns);
    proc_.patterns.namesFromVar(p.names);
    current_ = index;
    generatedName_ = {}; generatedCategory_ = {};
    ab_[(size_t)slot_] = proc_.apvts.copyState();
    return true;
}

void PresetManager::applyGenerated(const juce::NamedValueSet& values, const juce::var& patterns, const juce::var& names,
                                   const juce::String& name, const juce::String& category) {
    proc_.undoManager.beginNewTransaction("Ignite");
    setParameters(values);
    if (!keepPatterns) proc_.patterns.patternsFromVar(patterns);
    proc_.patterns.namesFromVar(names);
    current_ = -1;
    generatedName_ = name; generatedCategory_ = category;
    ab_[(size_t)slot_] = proc_.apvts.copyState();
}

bool PresetManager::saveUser(const juce::String& name, const juce::String& category, const juce::StringArray& tags) {
    if (name.trim().isEmpty()) return false;
    juce::XmlElement xml("ULPreset");
    xml.setAttribute("name", name.trim()); xml.setAttribute("category", category.isEmpty() ? juce::String("User") : category);
    xml.setAttribute("tags", tags.joinIntoString(","));
    for (auto* prm : proc_.getParameters())
        if (auto* r = dynamic_cast<juce::RangedAudioParameter*>(prm)) {
            auto* e = xml.createNewChildElement("PARAM");
            e->setAttribute("id", r->getParameterID());
            e->setAttribute("value", (double)r->convertFrom0to1(r->getValue()));
        }
    xml.createNewChildElement("PATTERNS")->addTextElement(juce::JSON::toString(proc_.patterns.patternsToVar(), true));
    xml.createNewChildElement("NAMES")->addTextElement(juce::JSON::toString(proc_.patterns.namesToVar(), true));
    auto folder = userFolder();
    if (!folder.createDirectory()) return false;
    const juce::String safe = juce::File::createLegalFileName(name.trim());
    if (!xml.writeTo(folder.getChildFile(safe + ".ulpreset"))) return false;
    reload();
    current_ = indexOf(name.trim());
    return true;
}

bool PresetManager::deleteUser(int index) {
    if (index < 0 || index >= (int)presets_.size() || presets_[(size_t)index].factory) return false;
    const bool ok = presets_[(size_t)index].file.deleteFile();
    reload();
    return ok;
}

void PresetManager::toggleAB() {
    ab_[(size_t)slot_] = proc_.apvts.copyState();
    slot_ = 1 - slot_;
    if (ab_[(size_t)slot_].isValid()) {
        proc_.undoManager.beginNewTransaction("A/B");
        proc_.apvts.replaceState(ab_[(size_t)slot_].createCopy());
    } else ab_[(size_t)slot_] = proc_.apvts.copyState();
}

void PresetManager::copyToOtherSlot() { ab_[(size_t)(1 - slot_)] = proc_.apvts.copyState(); }
