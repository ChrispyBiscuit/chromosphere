"""Derive ULTRA's ultraviolet solar images and icons from Chromosphere | EXO's orange ones.

The EXO images (corona_bg.jpg, solar_limb.png, icon_*.png; see EXO's docs/SOLAR_ASSETS.md) were generated by the
project owner. ULTRA shows the same star in extreme ultraviolet, where observatory images show the corona violet:
the warm highlights move from solar orange to violet, the darks stay neutral. As INFRA's make_red_assets.py.
Usage: python3 make_uv_assets.py <exo assets/img dir> <ultra dir>
Writes <ultra dir>/assets/img/{corona_bg.jpg,solar_limb.png} and <ultra dir>/installer/{icon_1024.png,icon_256.png,
ChromosphereUltra.ico}.
"""
import sys
import numpy as np
from PIL import Image


def uvshift(rgb, strength=1.0):
    x = rgb.astype(np.float32) / 255.0
    lum = 0.2126 * x[..., 0] + 0.7152 * x[..., 1] + 0.0722 * x[..., 2]
    # Warmth of the source pixel (orange highlights have r >> b); dark neutral pixels keep their grey, cooled a touch.
    warm = np.clip((x[..., 0] - x[..., 2]) * 4.0, 0.0, 1.0) * strength
    grey = np.stack([lum * 0.99, lum * 0.97, lum * 1.04], axis=-1)
    # Ultraviolet ramp: violet in the mid tones, a hot lavender-white only at the very top.
    hot = np.clip((lum - 0.55) * 2.2, 0.0, 1.0)[..., None]
    uv = np.stack([lum * 1.25, lum * 0.42, np.clip(lum * 2.6, 0, 1)], axis=-1)
    uv = uv * (1 - hot) + np.array([0.93, 0.84, 1.0]) * hot
    out = grey * (1 - warm[..., None]) + uv * warm[..., None]
    return (np.clip(out, 0, 1) * 255 + 0.5).astype(np.uint8)


def recolour_rgba(path):
    im = np.array(Image.open(path).convert("RGBA"))
    return Image.fromarray(np.dstack([uvshift(im[..., :3]), im[..., 3]]))


def main(src, dst):
    cor = np.array(Image.open(f"{src}/corona_bg.jpg").convert("RGB"))
    Image.fromarray(uvshift(cor)).save(f"{dst}/assets/img/corona_bg.jpg", quality=88)
    recolour_rgba(f"{src}/solar_limb.png").save(f"{dst}/assets/img/solar_limb.png", optimize=True)
    big = recolour_rgba(f"{src}/icon_1024.png")
    big.save(f"{dst}/installer/icon_1024.png", optimize=True)
    big.resize((256, 256), Image.LANCZOS).save(f"{dst}/installer/icon_256.png", optimize=True)
    big.save(f"{dst}/installer/ChromosphereUltra.ico", sizes=[(16, 16), (24, 24), (32, 32), (48, 48), (64, 64), (128, 128), (256, 256)])


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
