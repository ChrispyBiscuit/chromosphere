"""Derive MUON's blue solar images and icons from Chromosphere | EXO's orange ones.

The EXO images (corona_bg.jpg, solar_limb.png, icon_1024.png; see EXO's docs/SOLAR_ASSETS.md) were generated by the
project owner. MUON shows the star through the light its cosmic-ray muons make: Cherenkov blue. The warm highlights
move from solar orange to a deep electric blue, the darks stay neutral (the method of INFRA's make_red_assets.py).
Usage: python3 make_blue_assets.py <exo assets/img dir> <muon assets/img dir> <muon installer dir>
"""
import sys
import numpy as np
from PIL import Image


def blueshift(rgb, strength=1.0):
    x = rgb.astype(np.float32) / 255.0
    lum = 0.2126 * x[..., 0] + 0.7152 * x[..., 1] + 0.0722 * x[..., 2]
    # Warmth of the source pixel (orange highlights have r >> b); dark neutral pixels keep a cool grey.
    warm = np.clip((x[..., 0] - x[..., 2]) * 4.0, 0.0, 1.0) * strength
    grey = np.stack([lum * 0.98, lum * 1.0, lum * 1.03], axis=-1)
    # Cherenkov ramp: deep blue in the mid tones, an ice-white only at the very top.
    hot = np.clip((lum - 0.55) * 2.2, 0.0, 1.0)[..., None]
    blue = np.stack([lum * 0.22, np.clip(lum * 1.15, 0, 1), np.clip(lum * 2.6, 0, 1)], axis=-1)
    blue = blue * (1 - hot) + np.array([0.80, 0.92, 1.0]) * hot
    out = grey * (1 - warm[..., None]) + blue * warm[..., None]
    return (np.clip(out, 0, 1) * 255 + 0.5).astype(np.uint8)


def main(src, dst, installer):
    cor = np.array(Image.open(f"{src}/corona_bg.jpg").convert("RGB"))
    Image.fromarray(blueshift(cor)).save(f"{dst}/corona_bg.jpg", quality=88)
    limb = np.array(Image.open(f"{src}/solar_limb.png").convert("RGBA"))
    Image.fromarray(np.dstack([blueshift(limb[..., :3]), limb[..., 3]])).save(f"{dst}/solar_limb.png", optimize=True)
    icon = np.array(Image.open(f"{src}/icon_1024.png").convert("RGBA"))
    big = Image.fromarray(np.dstack([blueshift(icon[..., :3]), icon[..., 3]]))
    big.save(f"{installer}/icon_1024.png", optimize=True)
    big.resize((256, 256), Image.LANCZOS).save(f"{installer}/icon_256.png", optimize=True)
    big.save(f"{installer}/ChromosphereMuon.ico", sizes=[(16, 16), (24, 24), (32, 32), (48, 48), (64, 64), (128, 128), (256, 256)])


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2], sys.argv[3])
